ttl = 300                                         # 답을 저장해 써도 되는 초를 ttl 에 담는다
saved_at = 0                                      # 0초에 DNS 서버에 물어 답을 저장했다고 saved_at 에 담는다
for now in [30, 100, 299, 300]:                   # 지금 시각(초)을 리스트에서 하나씩 꺼내 now 에 담아 반복한다
    if now < saved_at + ttl:                      # 지금이 만료 시각(저장한 시각 + TTL)보다 작으면 아래 줄을 실행한다
        print(now, "초: 캐시의 답을 쓴다")        # 아직 만료 전이라 저장한 답을 쓴다고 출력한다
    else:                                         # 만료 시각과 같거나 지났으면 아래 줄을 실행한다
        print(now, "초: DNS 서버에 새로 묻는다")  # 만료되어 DNS 서버에 다시 묻는다고 출력한다
